"""Generate the fixed cube approximation of the rule-book L-shaped pit.

Maximum fill depth is 0.10 m (user specified). The rule specifies a 0.15 m railing,
2 m long edges, 1 m short edges, and 10--20 mm pine bark pieces.
The fill bottom is at exterior ground level; all dimensions are in metres.
"""

import argparse
import math
from pathlib import Path
import xml.etree.ElementTree as ET


DEPTH = 0.10
RAIL_HEIGHT = 0.15
RAIL_THICKNESS = 0.025  # Modeling assumption; not specified in the rules.


def numbers(values):
    return ' '.join(f'{value:.9g}' for value in values)


def geom(parent, name, pos, size, color):
    return ET.SubElement(parent, 'geom', name=name, type='box',
                         pos=numbers(pos), size=numbers(size), rgba=color,
                         friction='0.8 0.1 0.1', contype='1', conaffinity='1', condim='3')


def save(root, path):
    ET.indent(root, space='  ')
    path.write_text(ET.tostring(root, encoding='unicode') + '\n', encoding='utf-8')


def generate(output):
    bottom = 0.0
    output.mkdir(parents=True, exist_ok=True)
    geometry = ET.Element('mujocoinclude')
    geometry.append(ET.Comment(' Generated by generate_brick_wood_pit.py; dimensions in metres. '))
    geometry.append(ET.Comment(f' Fill bottom z={bottom:g}, maximum fill depth={DEPTH:g}; railing z=0..{RAIL_HEIGHT:g}. '))
    geometry.append(ET.Comment(' L outline: (0,-.5),(2,-.5),(2,1.5),(1,1.5),(1,.5),(0,.5). '))
    geometry.append(ET.Comment(' Brick/bark boundary x+y=1.5; no extra raised divider. '))
    assets_root = ET.Element('mujocoinclude')
    assets = ET.SubElement(assets_root, 'asset')
    t = RAIL_THICKNESS
    h = RAIL_HEIGHT/2
    walls = [
        ('entry', (t/2, 0, h), (t/2, .5, h)),
        ('bottom', (1, -.5+t/2, h), (1, t/2, h)),
        ('right', (2-t/2, .5, h), (t/2, 1, h)),
        ('exit', (1.5, 1.5-t/2, h), (.5, t/2, h)),
        ('inner_vertical', (1+t/2, 1, h), (t/2, .5, h)),
        ('inner_horizontal', (.5, .5-t/2, h), (.5, t/2, h)),
    ]
    for name, pos, size in walls:
        geom(geometry, 'pit_rail_' + name, pos, size, '0.25 0.55 0.18 1')

    # Convex trapezoidal bulk approximations avoid rendering hidden cube layers.
    polygons = {
        'brick': [(t, -.5+t), (2-t, -.5+t), (1+t, .5-t), (t, .5-t)],
        'bark': [(2-t, -.5+t), (2-t, 1.5-t), (1+t, 1.5-t), (1+t, .5-t)],
    }
    bulk_heights = {'brick': DEPTH-.05, 'bark': DEPTH-.02}
    colors = {'brick': '0.58 0.25 0.16 1', 'bark': '0.29 0.17 0.08 1'}
    for material, polygon in polygons.items():
        vertices = [(x, y, z) for z in (bottom, bottom+bulk_heights[material])
                    for x, y in polygon]
        ET.SubElement(assets, 'mesh', name=f'pit_{material}_bulk_mesh',
                      vertex=numbers(v for point in vertices for v in point))
        ET.SubElement(geometry, 'geom', name=f'pit_{material}_bulk', type='mesh',
                      mesh=f'pit_{material}_bulk_mesh', rgba=colors[material],
                      friction='0.8 0.1 0.1', contype='1', conaffinity='1', condim='3')

    # A deterministic four-size motif, shifted between rows. All pieces are cubes.
    # replicate expands to ordinary named static geoms; no movable granular bodies.
    specifications = [('brick', .06, (.03, .04, .05, .04)),
                      ('bark', .022, (.010, .014, .018, .020))]
    for material, pitch, edges in specifications:
        max_half = max(edges)/2
        y_start = -.5+t+pitch/2
        y_stop = (.5-t if material == 'brick' else 1.5-t)-max_half
        row_count = math.floor((y_stop-y_start)/pitch)+1
        x_start = t+pitch/2
        col_count = math.floor((2-t-max_half-x_start)/pitch)+1
        for row in range(row_count):
            y = y_start+row*pitch
            valid = []
            for col in range(col_count):
                x = x_start+col*pitch
                if material == 'brick':
                    inside = x+y+2*max_half <= 1.5+1e-9
                else:
                    inside = x-max_half >= 1+t-1e-9 and x+y-2*max_half >= 1.5-1e-9
                if inside:
                    valid.append(col)
            for phase in range(4):
                selected = [col for col in valid if col % 4 == phase]
                if not selected:
                    continue
                edge = edges[(phase+row) % 4]
                parent = ET.SubElement(geometry, 'replicate', count=str(len(selected)),
                                       offset=numbers((4*pitch, 0, 0)))
                x = x_start+selected[0]*pitch
                z = bottom+bulk_heights[material]+edge/2
                geom(parent, f'pit_{material}_r{row:02d}_p{phase}_', (x,y,z),
                     (edge/2,)*3, colors[material])

    save(assets_root, output/'brick_wood_pit_assets.xml')
    save(geometry, output/'brick_wood_pit.xml')

    source = Path(__file__).resolve().parent/'scene_primuus_high_wall.xml'
    scene = ET.parse(source).getroot()
    scene.set('model', 'primuus brick wood pit review')
    scene.insert(2, ET.Element('include', file='brick_wood_pit_assets.xml'))
    scene.find('statistic').set('center', '1.7 0.4 0.12')
    scene.find('statistic').set('extent', '4.5')
    world = scene.find('worldbody')
    body = world.find("body[@name='high_wall']")
    body.set('name', 'brick_wood_pit')
    body.find('include').set('file', 'brick_wood_pit.xml')
    for element in scene.iter():
        for key, value in list(element.attrib.items()):
            element.set(key, value.replace('high_wall_ground', 'brick_wood_pit_ground'))
    save(scene, output/'scene_primuus_brick_wood_pit.xml')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    generate(args.output_dir)
